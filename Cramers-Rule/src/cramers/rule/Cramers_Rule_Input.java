    private void applyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_applyActionPerformed
        // TODO add your handling code here:
        TableModel model = coeffients.getModel();
        CoeffientsTableModel coeffients_model = (model instanceof CoeffientsTableModel) ? (CoeffientsTableModel) model : null;
        if (coeffients_model != null) {
            TableModel answsers_model = coeffients_model.getAnswersTableModel();
            int ccount = coeffients_model.getColumnCount();
            int rcount = coeffients_model.getRowCount();
            String[] coefficents = new String[ccount];
            double[][] values;
            double[] answers;
            for (int i = 0; i < ccount; i++) {
                coefficents[i] = coeffients_model.getColumnName(i);
            }
            List<List<Number>> c_data = new ArrayList();
            List<Number> a_data = new ArrayList();
            boolean ok = true;
            for (int row = 0; ok && row < rcount; row++) {
                List<Number> data = new ArrayList();
                c_data.add(data);
                for (int column = 0; ok && column < ccount; column++) {
                    Object o = coeffients_model.getValueAt(row, column);
                    if (o instanceof Number) {
                        data.add((Number) o);
                    } else {
                        String s = String.valueOf(o).trim();
                        try {
                            Double d = new Double(s);
                            data.add(d);
                        } catch (Exception e) {
                            e.printStackTrace();
                            ok = false;
                        }
                    }
                }
            }
            for (int row = 0; ok && row < rcount; row++) {
                Object o = answsers_model.getValueAt(row, 0);
                if (o instanceof Number) {
                    a_data.add((Number) o);
                } else {
                    String s = String.valueOf(o).trim();
                    try {
                        Double d = new Double(s);
                        a_data.add(d);
                    } catch (Exception e) {
                        JOptionPane.showMessageDialog(this, e.getMessage(), getTitle(), JOptionPane.ERROR_MESSAGE);
                        ok = false;
                    }
                }
            }
            if (ok) {
                values = new double[rcount][ccount];
                for (int i = 0; i < rcount; i++) {
                    List<Number> data = c_data.get(i);
                    for (int j = 0; j < ccount; j++) {
                        Number n = data.get(j);
                        values[i][j] = n.doubleValue();
                    }
                }
                answers = new double[rcount];
                for (int i = 0; i < rcount; i++) {
                    Number n = a_data.get(i);
                    answers[i] = n.doubleValue();
                }
                solveCramer(coefficents, values, answers);
            }
        }
    }//GEN-LAST:event_applyActionPerformed

