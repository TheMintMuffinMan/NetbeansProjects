    class AnswersTableModel extends DefaultTableModel {

        public AnswersTableModel(int rowCount, int columnCount) {
            super(rowCount, columnCount);
        }

        public String getColumnName(int column) {
            return (column == 0) ? "Answers" : super.getColumnName(column);
        }

        public Class getColumnClass(int columnIndex) {
            return Double.class;
        }
    }

    class CoeffientsTableModel extends DefaultTableModel {

        String[] _vars = {
            "x",
            "y",
            "z",
            "a",
            "b",
            "c",
            "d",};
        private AnswersTableModel _answers;

        public CoeffientsTableModel(int rowCount, int columnCount) {
            super(rowCount, columnCount);
        }

        public String getColumnName(int column) {
            return ((column > -1) && (column < _vars.length)) ? _vars[column] : super.getColumnName(column);
        }

        public int getMaxCoefficentCounts() {
            return _vars.length;
        }

        public TableModel getAnswersTableModel() {
            int rcount = getRowCount();
            _answers = ((_answers != null) && _answers.getRowCount() == rcount) ? _answers : null;
            if (_answers == null) {
                _answers = new AnswersTableModel(rcount, 1);
            }
            return _answers;
        }

        public Class getColumnClass(int columnIndex) {
            return Double.class;
        }
    }

    class DeterminantTable extends JTable {

        int _which = -1;

        public DeterminantTable(int which, TableModel model) {
            super(model);
            _which = which;
        }

        public Component prepareRenderer(TableCellRenderer r, int data, int column) {
            Component c = super.prepareRenderer(r, data, column);
            if ((_which > -1) && (column == _which)) {
                c.setForeground(Color.red);
            } else {
                c.setForeground(Color.blue);
            }
            return c;
        }
    }
