    private TableModel copytoMatrixTableModel(double[][] values) {
        TableModel model = new DefaultTableModel(values.length, values.length) {
            public boolean isCellEditable(int row, int col) {
                return false;
            }

            public Class getColumnClass(int columnIndex) {
                return Double.class;
            }
        };
        int ccount = model.getColumnCount();
        int rcount = model.getColumnCount();
        for (int row = 0; row < rcount; row++) {
            for (int col = 0; col < ccount; col++) {
                model.setValueAt(values[row][col], row, col);
            }
        }
        return model;
    }

    private boolean solveCramer(String[] coefficents, double[][] values, double[] answers) {
        int rcount = answers.length;
        int ccount = coefficents.length;
        //create all the matricies and solve them
        JPanel grid = new JPanel(new GridLayout(coefficents.length + 1, 1, 8, 8));
        //add the base matrix
        JFrame frame = new JFrame();
        frame.setDefaultCloseOperation(javax.swing.WindowConstants.DISPOSE_ON_CLOSE);
        frame.setTitle("Cramer's Rule: Solution");
        frame.add(grid);
        int which = -1;
        double dn = 1;
        do {
            double[][] data = new double[values.length][values.length];
            for (int row = 0; row < data.length; row++) {
                for (int col = 0; col < data.length; col++) {
                    data[row][col] = values[row][col];
                }
            }
            JPanel p = new JPanel(new BorderLayout(5, 5));
            String label = "D ";
            if (which != -1) {
                label = "D" + coefficents[which];
                //replace the coefficent column with the answer column
                for (int row = 0; row < answers.length; row++) {
                    data[row][which] = answers[row];
                }
            }
            double answer = 0.0;
            if (which > -1) {
                answer = computeDeterminant(data) / dn;
            } else {
                dn = computeDeterminant(data);
                answer = dn;
            }
            //JLabel l = new JLabel(label);
            //l.setHorizontalAlignment(JLabel.LEFT);
            //p.add(l, BorderLayout.NORTH);
            p.setBorder(BorderFactory.createTitledBorder(label));
            JTable matrix = new DeterminantTable(which, copytoMatrixTableModel(data));
            p.add(matrix, BorderLayout.CENTER);
            NumberFormat formatter = NumberFormat.getInstance();
            label = (which == -1) ? "Coefficient Determinant" : coefficents[which];
            JLabel l = new JLabel(label += " = " + formatter.format(answer));
            l.setHorizontalAlignment(JLabel.RIGHT);
            p.add(l, BorderLayout.SOUTH);
            grid.add(p);
            which++;
        } while (which < coefficents.length);
        frame.pack();
        frame.setVisible(true);
        return true;
    }

    private double computeDeterminant(double[][] data) {
        int ccount = data.length;
        NumberFormat format = NumberFormat.getInstance();
        double value = 0.0;
        if (ccount == 2) {
            double a = data[0][0];
            double b = data[0][1];
            double c = data[1][0];
            double d = data[1][1];
            return (a * d) - (b * c);
        }
        boolean pos = true;
        for (int d_col = 0; d_col < ccount; d_col++) {
            double d = data[0][d_col];
            double[][] n_data = new double[ccount - 1][ccount - 1];
            int n_row = 0;
            for (int row = 1; row < ccount; row++) {
                int n_col = 0;
                for (int col = 0; col < ccount; col++) {
                    if (d_col != col) {
                        n_data[n_row][n_col++] = data[row][col];
                    }
                }
                n_row++;
            }
            double d_value = d * computeDeterminant(n_data);
            if (pos) {
                value += d_value;
                pos = false;
            } else {
                value -= d_value;
                pos = true;
            }
        }
        return value;
    }

